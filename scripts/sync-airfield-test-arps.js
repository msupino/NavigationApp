#!/usr/bin/env node
/**
 * Regenerate tests/_airfieldArp.js from docs/airfields.json (ICAO ARPs).
 * Run after chart / airfield position updates:
 *   node scripts/sync-airfield-test-arps.js
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const jsonPath = path.join(root, 'docs', 'airfields.json');
const outPath = path.join(root, 'tests', '_airfieldArp.js');

const data = JSON.parse(fs.readFileSync(jsonPath, 'utf8'));

function arp(code) {
  const a = data.airfields.find(x => x.name === code);
  if (!a) throw new Error('Missing ' + code + ' in ' + jsonPath);
  return { lat: a.lat, lng: a.lng, name: code };
}

for (const code of ['LLHZ', 'LLHA', 'LLBG']) arp(code); // validate

const body = [
  '// @ts-check',
  '/**',
  ' * Published ARP lat/lng from `docs/airfields.json` for Playwright fixtures.',
  ' * **Generated by** `node scripts/sync-airfield-test-arps.js` — re-run after',
  ' * airfield chart position changes.',
  ' */',
  "const data = require('../docs/airfields.json');",
  '',
  '/** @param {string} code */',
  'function arp(code) {',
  "  const a = data.airfields.find(x => x.name === code);",
  "  if (!a) throw new Error('docs/airfields.json missing airfield ' + code);",
  '  return { lat: a.lat, lng: a.lng, name: code };',
  '}',
  '',
  "const LLHZ = arp('LLHZ');",
  "const LLHA = arp('LLHA');",
  "const LLBG = arp('LLBG');",
  '',
  '/** @returns {{ lat: number, lng: number, name: string }[]} */',
  'function pairLLHZ_LLHA() {',
  '  return [',
  "    { lat: LLHZ.lat, lng: LLHZ.lng, name: 'LLHZ' },",
  "    { lat: LLHA.lat, lng: LLHA.lng, name: 'LLHA' },",
  '  ];',
  '}',
  '',
  'module.exports = { arp, LLHZ, LLHA, LLBG, pairLLHZ_LLHA };',
  '',
].join('\n');

fs.writeFileSync(outPath, body);
console.log('Wrote', path.relative(root, outPath));
