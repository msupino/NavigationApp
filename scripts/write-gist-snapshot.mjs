#!/usr/bin/env node
// Write the live tuning gist into the app as data/gist-snapshot.js, so an app that has never been
// online -- a fresh APK opened in the aeroplane -- starts with the gist's settings, not only the
// built-in defaults. core.js applies it between the built-in defaults and the gist this device
// last downloaded (docs/app/core.js, applyBundledGist).
//
//   node scripts/write-gist-snapshot.mjs [out.js]      (default docs/data/gist-snapshot.js)
//
// Run by every deploy (.github/workflows/deploy.yml) and by `npm run embed` (the APK). A gist
// that cannot be fetched, or is not a JSON object, leaves the file as it is and exits 0: a
// deploy is not worth failing over a snapshot one build old.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const GIST_URL = 'https://gist.githubusercontent.com/msupino/12c6e9d9dfcd783ffbeaa06246783840/raw/navaid-config.json';
export const DEFAULT_OUT = path.join(root, 'docs', 'data', 'gist-snapshot.js');

// What goes into a file the app EXECUTES: setting names, and plain values -- a number, a string,
// true/false, null. Anything else the gist might carry (a nested object, an odd key) is dropped
// rather than written. JSON.stringify of what is left is a JavaScript literal and nothing more.
export function cleanConfig(config) {
  const out = {};
  for (const [k, v] of Object.entries(config || {})) {
    if (!/^[A-Za-z][A-Za-z0-9_]{0,63}$/.test(k)) continue;
    const t = typeof v;
    if (v === null || t === 'boolean' || (t === 'number' && Number.isFinite(v)) || (t === 'string' && v.length <= 400)) out[k] = v;
  }
  return out;
}

export function snapshotSource(config, fetchedAt) {
  config = cleanConfig(config);
  return '// Generated by scripts/write-gist-snapshot.mjs from the live tuning gist -- do not edit.\n'
    + '// ' + GIST_URL + '\n'
    + 'window.__navaidGistSnapshot = ' + JSON.stringify(config, null, 1) + ';\n'
    + 'window.__navaidGistSnapshotAt = ' + JSON.stringify(fetchedAt) + ';\n';
}

export async function writeSnapshot(out = DEFAULT_OUT) {
  try {
    const res = await fetch(GIST_URL + '?t=' + Date.now(), { cache: 'no-store' });
    if (!res.ok) throw new Error('HTTP ' + res.status);
    const config = await res.json();
    if (!config || typeof config !== 'object' || Array.isArray(config)) throw new Error('not a JSON object');
    const clean = cleanConfig(config);
    if (!Object.keys(clean).length) throw new Error('no settings in it');
    fs.mkdirSync(path.dirname(out), { recursive: true });
    fs.writeFileSync(out, snapshotSource(clean, new Date().toISOString()));
    return { ok: true, keys: Object.keys(clean).length };
  } catch (e) {
    return { ok: false, reason: e.message };
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = path.resolve(process.argv[2] || DEFAULT_OUT);
  writeSnapshot(out).then((r) => {
    if (r.ok) console.error('gist snapshot: %d keys -> %s', r.keys, path.relative(root, out));
    else console.error('::warning::gist snapshot not refreshed (%s); keeping %s', r.reason, path.relative(root, out));
  });
}
